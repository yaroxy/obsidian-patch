import esbuild from "esbuild";
import { builtinModules } from "node:module";
import { readFile, mkdir, copyFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import process from "node:process";
import { gzipSync } from "node:zlib";
import { BUILD_TARGETS, RELEASE_FILES, fileHash, sourceHashes, validateMermaidInputs, validateReleaseMetadata } from "./scripts/lib/release-validation.mjs";

const production = process.argv[2] === "production";
const target = process.argv[3] ?? "community";
if (!BUILD_TARGETS.includes(target)) throw new Error(`Unknown build target: ${target}`);
if (process.argv[2] && !["production", "development"].includes(process.argv[2])) throw new Error("Expected production or development");
const root = fileURLToPath(new URL("./", import.meta.url));
const outputDir = join(root, "dist", target);
const require = createRequire(import.meta.url);
validateReleaseMetadata(root);

/**
 * Resolves `gzip:<package path>` imports to the file's gzip-compressed bytes
 * as a base64 string. Large data such as icon packs stays inside main.js, so
 * nothing is fetched at runtime, but costs far less to ship and to parse.
 */
const gzipModules = {
  name: "gzip-modules",
  setup(build) {
    build.onResolve({ filter: /^gzip:/ }, (args) => ({
      path: require.resolve(args.path.slice("gzip:".length)),
      namespace: "gzip",
    }));

    build.onLoad({ filter: /.*/, namespace: "gzip" }, async (args) => {
      const compressed = gzipSync(await readFile(args.path), { level: 9 });
      return {
        contents: `export default ${JSON.stringify(compressed.toString("base64"))};`,
        loader: "js",
        watchFiles: [args.path],
      };
    });
  },
};

const distribution = {
  name: "patches-distribution",
  setup(build) {
    build.onStart(() => { validateReleaseMetadata(root); });
    if (target === "full") {
      build.onResolve({ filter: /(?:^|\/)mermaid-runtime(?:\.ts)?$/ }, args => {
        const resolved = resolve(args.resolveDir, args.path.replace(/\.ts$/, ""));
        if (resolved === join(root, "src/features/mermaid-runtime")) {
          return { path: join(root, "src/features/mermaid-runtime/full.ts") };
        }
      });
    }
    build.onLoad({ filter: /[/\\]src[/\\]main\.ts$/ }, async args => ({
      contents: await readFile(args.path, "utf8"), loader: "ts", resolveDir: dirname(args.path),
      watchFiles: ["manifest.json", "styles.css", "package.json", "package-lock.json", "versions.json"].map(file => join(root, file)),
    }));
    build.onEnd(async result => {
      if (result.errors.length) return;
      validateMermaidInputs(result.metafile, target);
      const manifest = validateReleaseMetadata(root);
      await mkdir(outputDir, { recursive: true });
      for (const file of ["manifest.json", "styles.css"]) await copyFile(join(root, file), join(outputDir, file));
      const info = {
        target, production, version: manifest.version, minAppVersion: manifest.minAppVersion,
        mermaidVersion: require("mermaid/package.json").version,
        files: Object.fromEntries(RELEASE_FILES.map(file => [file, fileHash(join(outputDir, file))])),
        sources: sourceHashes(root, result.metafile),
      };
      await writeFile(join(outputDir, "metafile.json"), JSON.stringify(result.metafile, null, 2) + "\n");
      await writeFile(join(outputDir, "build-info.json"), JSON.stringify(info, null, 2) + "\n");
    });
  },
};

const context = await esbuild.context({
  absWorkingDir: root,
  banner: {
    js: "/* Generated by esbuild. See the project source for the readable code. */",
  },
  entryPoints: ["src/main.ts"],
  bundle: true,
  define: {
    __BUNDLED_MERMAID_VERSION__: JSON.stringify(require("mermaid/package.json").version),
  },
  external: [
    "obsidian",
    "electron",
    "@codemirror/autocomplete",
    "@codemirror/collab",
    "@codemirror/commands",
    "@codemirror/language",
    "@codemirror/lint",
    "@codemirror/search",
    "@codemirror/state",
    "@codemirror/view",
    "@lezer/common",
    "@lezer/highlight",
    "@lezer/lr",
    ...builtinModules,
  ],
  format: "cjs",
  logLevel: "info",
  minify: production,
  outfile: join(outputDir, "main.js"),
  metafile: true,
  plugins: [distribution, gzipModules],
  sourcemap: production ? false : "inline",
  target: "es2021",
  treeShaking: true,
});

if (production) {
  await context.rebuild();
  await context.dispose();
} else {
  await context.watch();
}

